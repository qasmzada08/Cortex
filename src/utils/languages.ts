const RTL_CODES = new Set(['ar', 'he', 'iw', 'fa', 'ur', 'ps', 'sd', 'dv', 'yi', 'ku', 'ckb']);

const RTL_SCRIPT_REGEX = /[\u0590-\u05FF\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]/;

export function isRtlLanguage(languageInput: string): boolean {
  const normalized = languageInput.trim().toLowerCase();
  if (!normalized) return false;
  if (RTL_CODES.has(normalized)) return true;
  if (RTL_SCRIPT_REGEX.test(languageInput)) return true;
  return RTL_KEYWORDS.some((kw) => normalized.includes(kw));
}

export function resolveLanguageMeta(languageInput: string): {
  name: string;
  code: string;
  rtl: boolean;
} {
  const trimmed = languageInput.trim();
  if (!trimmed) {
    return { name: 'English', code: 'en', rtl: false };
  }

  const lower = trimmed.toLowerCase();
  const matched = WORLD_LANGUAGES.find(
    (lang) =>
      lang.code.toLowerCase() === lower ||
      lang.name.toLowerCase() === lower ||
      lang.nativeName.toLowerCase() === lower
  );

  if (matched) {
    return {
      name: matched.name,
      code: matched.code,
      rtl: matched.rtl,
    };
  }

  const rtl = isRtlLanguage(trimmed);
  const derivedCode = trimmed
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 12) || 'custom';

  return {
    name: trimmed,
    code: derivedCode,
    rtl,
  };
}
